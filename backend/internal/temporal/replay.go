package temporal

import (
	"github.com/google/uuid"
	"github.com/shopspring/decimal"
)

// MaxReplayBatchItems bounds one offline replay batch.
//
// The whole batch travels as a workflow input, and Temporal caps a single gRPC message at
// 4 MB. The limit is deliberately far below that: the point is to reject an unreasonable
// batch at the edge with a status the client can act on, rather than let one workflow carry
// an unbounded payload into a worker and fail inside it. A client with more queued than this
// drains it over several batches.
const MaxReplayBatchItems = 100

// ReplayItem is one queued offline transaction, as submitted by the browser and replayed by
// the worker.
//
// It lives next to SyncScope rather than in the workflows package because the API handler
// that starts the workflow has to build the items, and internal/transaction cannot import
// the workflow packages: workflows import the replay activities, which import the
// transaction service. Same inversion as demo.ResetWorkflow and simplefin.ClaimWorkflow.
//
// ClientID is the idempotency key. It is generated by the client before the first attempt
// and never changes for a queued item, which is what lets a retried activity report success
// instead of creating a second transaction.
type ReplayItem struct {
	ClientID        string          `json:"client_id"`
	AccountID       uuid.UUID       `json:"account_id"`
	Amount          decimal.Decimal `json:"amount"`
	MerchantRaw     string          `json:"merchant_raw"`
	CategoryID      *uuid.UUID      `json:"category_id"`
	TransactionDate string          `json:"transaction_date"`
	UserNotes       string          `json:"user_notes,omitempty"`
}
